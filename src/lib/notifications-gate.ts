/**
 * Κεντρικός διακόπτης για τα ΑΥΤΟΜΑΤΑ email.
 *
 * ΞΕΚΙΝΑ ΚΛΕΙΣΤΟΣ. Όσο χτίζεται η λογική των ειδοποιήσεων, τίποτα δεν πρέπει
 * να φεύγει προς πραγματικούς παραλήπτες: μια λάθος συνθήκη σε cron δεν
 * ανακαλείται αφού σταλεί, και ήδη μία φορά παραλίγο να σταλούν 368 λανθασμένες
 * ειδοποιήσεις λήξης.
 *
 * ΤΙ ΚΑΛΥΠΤΕΙ: ό,τι στέλνεται χωρίς άνθρωπο στη μέση — ειδοποιήσεις
 * αποκλίσεων, ημερήσια σύνοψη, ειδοποιήσεις λήξης συμβάσεων.
 *
 * ΤΙ ΔΕΝ ΚΑΛΥΠΤΕΙ: τα συναλλακτικά email που ενεργοποιεί ρητά κάποιος —
 * επαναφορά κωδικού, έγκριση πρόσβασης στο portal, φόρμα επικοινωνίας. Αν
 * σταματούσαν κι αυτά, η εφαρμογή θα έσπαγε για τους χρήστες της.
 *
 * Ενεργοποίηση: `AUTOMATED_EMAILS_ENABLED=true` — χωρίς νέα έκδοση.
 */

export function automatedEmailsEnabled(): boolean {
  return process.env.AUTOMATED_EMAILS_ENABLED === "true";
}

/** Μήνυμα για τα logs, ώστε να μη φαίνεται σαν σιωπηλή αποτυχία. */
export function automatedEmailsBlockedMessage(what: string): string {
  return (
    `[EMAIL] ${what}: ΔΕΝ ΣΤΑΛΘΗΚΕ — τα αυτόματα email είναι απενεργοποιημένα. ` +
    "Όρισε AUTOMATED_EMAILS_ENABLED=true για να ενεργοποιηθούν."
  );
}
